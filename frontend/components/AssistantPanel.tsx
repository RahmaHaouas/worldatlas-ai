"use client";
import { Fragment, useEffect, useRef, useState, type ReactNode } from "react";
import { api } from "@/lib/api";
import type { AssistantAnswer } from "@/lib/types";
import { ErrorBox, Pill } from "./ui";

interface Message {
  role: "user" | "assistant";
  text: string;
  answer?: AssistantAnswer;
  error?: string;
}

interface Props {
  pending: string | null;
  clearPending: () => void;
  onHighlight: (iso3s: string[] | null, label?: string) => void;
  messages: Message[];
  setMessages: (fn: (m: Message[]) => Message[]) => void;
}

export type { Message as AssistantMessage };

const EXAMPLES = [
  "What is Tunisia famous for?",
  "Compare Tunisia and Spain in olive oil exports.",
  "Which countries export the most cocoa?",
  "What are Japan's technological specialties?",
  "Which countries have significant phosphate resources?",
  "Show countries with strong renewable energy development.",
];

/** Render answer text, turning [n] into citation chips. */
function withCitations(text: string, answer?: AssistantAnswer): ReactNode {
  const parts = text.split(/(\[\d+\])/g);
  return parts.map((part, i) => {
    const m = part.match(/^\[(\d+)\]$/);
    if (!m) return <Fragment key={i}>{part}</Fragment>;
    const rec = answer?.records.find((r) => r.id === Number(m[1]));
    return (
      <a key={i} href={rec?.source_url || "#"} target="_blank" rel="noreferrer" title={rec ? `${rec.source_org}: ${rec.text}` : undefined}
        className="mx-0.5 inline-flex h-4 min-w-4 items-center justify-center rounded bg-sky-500/20 px-1 align-text-top text-[10px] font-semibold text-sky-200 hover:bg-sky-500/40">
        {m[1]}
      </a>
    );
  });
}

export default function AssistantPanel({ pending, clearPending, onHighlight, messages, setMessages }: Props) {
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const scroller = useRef<HTMLDivElement | null>(null);

  const ask = async (q: string) => {
    const question = q.trim();
    if (!question || busy) return;
    setInput("");
    setBusy(true);
    setMessages((m) => [...m, { role: "user", text: question }]);
    try {
      const a = await api.ask(question);
      setMessages((m) => [...m, { role: "assistant", text: a.answer, answer: a }]);
      onHighlight(a.highlight_countries.length ? a.highlight_countries : null, "AI answer");
    } catch (e) {
      setMessages((m) => [...m, { role: "assistant", text: "", error: e instanceof Error ? e.message : String(e) }]);
    } finally {
      setBusy(false);
    }
  };

  useEffect(() => {
    if (pending) {
      clearPending();
      void ask(pending);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [pending]);

  useEffect(() => {
    scroller.current?.scrollTo({ top: scroller.current.scrollHeight, behavior: "smooth" });
  }, [messages, busy]);

  return (
    <div className="flex h-full flex-col">
      <header className="border-b border-white/5 p-5">
        <h2 className="font-display text-lg font-semibold text-white">WorldAtlas AI Assistant</h2>
        <p className="mt-1 text-xs text-slate-400">Answers are generated by Amazon Bedrock from retrieved, sourced WorldAtlas records only — with citations. Countries mentioned are shown on the map.</p>
      </header>

      <div ref={scroller} className="flex-1 space-y-4 overflow-y-auto p-5" aria-live="polite">
        {messages.length === 0 && (
          <div>
            <p className="text-sm text-slate-300">Try one of these questions:</p>
            <div className="mt-3 flex flex-col gap-2">
              {EXAMPLES.map((q) => (
                <button key={q} onClick={() => ask(q)} className="rounded-xl bg-ink-800/80 px-3 py-2 text-left text-sm text-slate-200 ring-1 ring-white/5 hover:ring-sky-500/40">
                  {q}
                </button>
              ))}
            </div>
          </div>
        )}
        {messages.map((m, i) =>
          m.role === "user" ? (
            <div key={i} className="ml-auto max-w-[85%] rounded-2xl rounded-br-sm bg-sky-500/20 px-4 py-2 text-sm text-sky-50 ring-1 ring-sky-500/30">{m.text}</div>
          ) : m.error ? (
            <ErrorBox key={i} message={m.error} />
          ) : (
            <div key={i} className="max-w-[95%] rounded-2xl rounded-bl-sm bg-ink-800/90 px-4 py-3 text-sm leading-relaxed text-slate-200 ring-1 ring-white/5">
              <div className="whitespace-pre-line">{withCitations(m.text, m.answer)}</div>
              {m.answer && (
                <>
                  <div className="mt-3 flex flex-wrap items-center gap-1.5">
                    <Pill className={m.answer.mode === "rag" ? "bg-violet-500/15 text-violet-300 ring-violet-500/30" : "bg-white/5 text-slate-400 ring-white/10"}>
                      {m.answer.mode === "rag" ? "Amazon Bedrock · grounded" : m.answer.mode === "extractive-fallback" ? "Retrieved records (model unavailable)" : "No matching data"}
                    </Pill>
                    {m.answer.highlight_countries.length > 0 && (
                      <button onClick={() => onHighlight(m.answer!.highlight_countries, "AI answer")} className="text-[11px] text-sky-300 hover:underline">
                        Show {m.answer.highlight_countries.length} on map
                      </button>
                    )}
                  </div>
                  {m.answer.sources.length > 0 && (
                    <details className="mt-2 text-xs text-slate-400">
                      <summary className="cursor-pointer select-none text-slate-300">Sources ({m.answer.sources.length})</summary>
                      <ol className="mt-1 space-y-1">
                        {m.answer.sources.map((s) => (
                          <li key={s.id}>
                            <span className="text-sky-300">[{s.id}]</span>{" "}
                            <a href={s.url} target="_blank" rel="noreferrer" className="hover:underline">{s.organization}</a>
                            <span className="block text-[11px] text-slate-500">{s.excerpt}</span>
                          </li>
                        ))}
                      </ol>
                    </details>
                  )}
                  {m.answer.related_questions.length > 0 && (
                    <div className="mt-3 flex flex-wrap gap-1.5">
                      {m.answer.related_questions.map((q) => (
                        <button key={q} onClick={() => ask(q)} className="rounded-full bg-white/5 px-2.5 py-1 text-[11px] text-slate-300 ring-1 ring-white/10 hover:bg-white/10">{q}</button>
                      ))}
                    </div>
                  )}
                </>
              )}
            </div>
          ),
        )}
        {busy && (
          <div className="flex items-center gap-2 text-xs text-slate-400">
            <span className="h-3 w-3 animate-spin rounded-full border-2 border-violet-400 border-t-transparent" /> Retrieving records and asking Bedrock…
          </div>
        )}
      </div>

      <form onSubmit={(e) => { e.preventDefault(); void ask(input); }} className="border-t border-white/5 p-4">
        <div className="flex gap-2">
          <input value={input} onChange={(e) => setInput(e.target.value)} maxLength={500} placeholder="Ask about any country or product…" aria-label="Ask the assistant"
            className="flex-1 rounded-xl bg-ink-800 px-4 py-2.5 text-sm text-white placeholder-slate-500 outline-none ring-1 ring-white/10 focus:ring-violet-500/60" />
          <button disabled={busy || !input.trim()} className="rounded-xl bg-violet-500/80 px-4 text-sm font-medium text-white hover:bg-violet-500 disabled:opacity-40">Ask</button>
        </div>
      </form>
    </div>
  );
}
